CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_consulta VARCHAR(8) NOT NULL,
    cliente_id BIGINT NOT NULL,
    endereco_entrega VARCHAR(500) NOT NULL,
    prazo_entrega DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_pedidos_codigo_consulta UNIQUE (codigo_consulta),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT ck_pedidos_codigo_consulta CHECK (CHAR_LENGTH(codigo_consulta) = 8),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('CRIADO', 'EM_SEPARACAO', 'DESPACHADO', 'EM_TRANSITO', 'ENTREGUE', 'CANCELADO'))
);

CREATE INDEX IF NOT EXISTS ix_pedidos_cliente ON pedidos (cliente_id);
CREATE INDEX IF NOT EXISTS ix_pedidos_status ON pedidos (status);

CREATE TABLE IF NOT EXISTS pedido_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    CONSTRAINT fk_pedido_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_pedido_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT uk_pedido_itens_produto UNIQUE (pedido_id, produto_id),
    CONSTRAINT ck_pedido_itens_quantidade CHECK (quantidade > 0)
);

CREATE INDEX IF NOT EXISTS ix_pedido_itens_produto ON pedido_itens (produto_id);

CREATE TABLE IF NOT EXISTS pedido_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_pedido_historico_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_pedido_historico_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_pedido_historico_status CHECK (status IN ('CRIADO', 'EM_SEPARACAO', 'DESPACHADO', 'EM_TRANSITO', 'ENTREGUE', 'CANCELADO'))
);

CREATE INDEX IF NOT EXISTS ix_pedido_historico_pedido ON pedido_historico (pedido_id);
CREATE INDEX IF NOT EXISTS ix_pedido_historico_usuario ON pedido_historico (usuario_id);
