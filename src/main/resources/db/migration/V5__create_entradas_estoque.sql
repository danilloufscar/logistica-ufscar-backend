ALTER TABLE produtos ADD COLUMN saldo INTEGER NOT NULL DEFAULT 0;
ALTER TABLE produtos ADD CONSTRAINT ck_produtos_saldo CHECK (saldo >= 0);

CREATE TABLE movimentacoes_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    quantidade INTEGER NOT NULL,
    data DATE NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_movimentacoes_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT fk_movimentacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_movimentacoes_tipo CHECK (tipo = 'ENTRADA'),
    CONSTRAINT ck_movimentacoes_quantidade CHECK (quantidade > 0)
);

CREATE INDEX ix_movimentacoes_produto_data ON movimentacoes_estoque (produto_id, data, id);
CREATE INDEX ix_movimentacoes_usuario ON movimentacoes_estoque (usuario_id);
