CREATE TABLE IF NOT EXISTS pedido_ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    descricao VARCHAR(500) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_pedido_ocorrencias_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_pedido_ocorrencias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_pedido_ocorrencias_descricao CHECK (CHAR_LENGTH(TRIM(descricao)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_pedido_ocorrencias_pedido ON pedido_ocorrencias (pedido_id);
CREATE INDEX IF NOT EXISTS ix_pedido_ocorrencias_usuario ON pedido_ocorrencias (usuario_id);